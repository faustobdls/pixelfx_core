Map<String, PixelGlyph> _buildGlyphs(Map<String, String> table, int h) {
  final out = <String, PixelGlyph>{};
  for (final entry in table.entries) {
    final rows = entry.value.split('|');
    if (rows.length != h) {
      throw StateError(
          'glyph ${entry.key} has ${rows.length} rows, expected $h');
    }
    out[entry.key] = PixelGlyph(
      width: rows[0].length,
      rows: [
        for (final row in rows)
          [for (var i = 0; i < row.length; i++) row[i] == '#'],
      ],
    );
  }
  return out;
}

final Map<PixelFontKind, PixelFont> pixelFonts = {
  PixelFontKind.mini: PixelFont(
    height: 5,
    space: 2,
    gap: 1,
    glyphs: _buildGlyphs(_miniSource, 5),
  ),
  PixelFontKind.big: PixelFont(
    height: 7,
    space: 3,
    gap: 1,
    glyphs: _buildGlyphs(_bigSource, 7),
  ),
};

/// Width in font pixels of [str] (before scaling).
int textWidth(String str, [PixelFontKind font = PixelFontKind.mini]) {
  final f = pixelFonts[font]!;
  var w = 0;
  for (var i = 0; i < str.length; i++) {
    final ch = str[i];
    final g = f.glyphs[ch] ?? f.glyphs[ch.toUpperCase()];
    w += (g != null ? g.width : f.space) + f.gap;
  }
  return w > f.gap ? w - f.gap : 0;
}

/// Calls [plot] for every inked font pixel of [str], top-left at (0, 0).
void rasterText(
  String str,
  PixelFontKind font,
  void Function(int x, int y) plot,
) {
  final f = pixelFonts[font]!;
  var x = 0;
  for (var i = 0; i < str.length; i++) {
    final ch = str[i];
    final g = f.glyphs[ch] ?? f.glyphs[ch.toUpperCase()];
    if (g == null) {
      x += f.space + f.gap;
      continue;
    }
    for (var r = 0; r < f.height; r++) {
      final row = g.rows[r];
      for (var c = 0; c < g.width; c++) {
        if (row[c]) plot(x + c, r);
      }
    }
    x += g.width + f.gap;
  }
}
