// Two pixel fonts: "mini" (3x5) for small numbers and tags, "big" (5x7) for words like LEVEL UP.
// Glyphs are trimmed to their inked columns, so text sets proportionally (an I is narrower than an M).

enum PixelFontKind { mini, big }

class PixelGlyph {
  final int width;
  final List<List<bool>> rows;

  const PixelGlyph({required this.width, required this.rows});
}

class PixelFont {
  final int height;
  final int space;
  final int gap;
  final Map<String, PixelGlyph> glyphs;

  const PixelFont({
    required this.height,
    required this.space,
    required this.gap,
    required this.glyphs,
  });
}

